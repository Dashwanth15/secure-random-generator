@app.route('/api/generate-value', methods=['POST', 'GET'])
def generate_value():
    """
    Generate a cryptographically secure random value for a Key, Nonce, Session ID, or Token.
    Backed by Python's `secrets` module and OS kernel entropy.
    """
    if request.method == 'POST':
        data = request.get_json(silent=True) or {}
        val_type = str(data.get('type', 'key')).strip().lower()
        try:
            length = int(data.get('length', TYPE_INFO.get(val_type, {}).get('default_length', 32)))
        except (ValueError, TypeError):
            length = 32
    else:
        val_type = str(request.args.get('type', 'key')).strip().lower()
        try:
            length = int(request.args.get('length', TYPE_INFO.get(val_type, {}).get('default_length', 32)))
        except (ValueError, TypeError):
            length = 32

    if val_type not in TYPE_INFO:
        val_type = "key"

    info = TYPE_INFO[val_type]
    if length not in info["valid_lengths"]:
        length = info["default_length"]

    # Generate raw secure bytes using OS CSPRNG
    raw_bytes = secrets.token_bytes(length)
    hex_value = raw_bytes.hex()
    bits = length * 8
    hex_chars = len(hex_value)

    if val_type == "session":
        active_sessions.add(hex_value)
    elif val_type == "token":
        active_tokens.add(hex_value)

    return jsonify({
        "type": val_type,
        "type_title": info["title"],
        "icon": info["icon"],
        "bytes": length,
        "bits": bits,
        "hex_chars": hex_chars,
        "value": hex_value,
        "generator": "CSPRNG",
        "source": "Python secrets module / os.urandom",
        "entropy": f"~{bits} bits (full OS entropy)",
        "purpose": info["purpose"],
        "explanation": info["explanation"],
        "strength": "CRYPTOGRAPHICALLY SECURE"
    })


