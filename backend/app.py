# 2. KEY DEMO — ENCRYPT & AUTHENTICATED DECRYPT
# ===========================================================================
@app.route('/api/encrypt', methods=['POST'])
def encrypt_message():
    """Encrypt plaintext message using Fernet authenticated encryption with the exact supplied key."""
    data = request.get_json(silent=True)
    if not data:
        return jsonify({"error": "Request body must be JSON."}), 400

    message = str(data.get('message', '')).strip()
    key_str = str(data.get('key', '')).strip()

    if not message:
        return jsonify({"error": "Message cannot be empty."}), 400
    if len(message) > MAX_MESSAGE_LENGTH:
        return jsonify({"error": f"Message too long. Max {MAX_MESSAGE_LENGTH} characters."}), 400
    if not key_str:
        return jsonify({"error": "Key cannot be empty."}), 400

    try:
        fernet_key = derive_fernet_key(key_str)
        fernet = Fernet(fernet_key)
        ciphertext = fernet.encrypt(message.encode('utf-8')).decode('utf-8')

        return jsonify({
            "ciphertext": ciphertext,
            "original_length": len(message),
            "ciphertext_length": len(ciphertext),
            "algorithm": "Fernet (AES-128-CBC + HMAC-SHA256)",
            "key_used": key_str,
            "note": "Ciphertext includes IV, timestamp, and HMAC-SHA256 authentication tag"
        })
    except Exception as e:
        return jsonify({"error": f"Encryption failed: {str(e)}"}), 400


@app.route('/api/verify-decrypt', methods=['POST'])
def verify_decrypt():
    """Attempt authenticated decryption with user-supplied key."""
    data = request.get_json(silent=True)
    if not data:
        return jsonify({"error": "Request body must be JSON."}), 400

    key_attempt = str(data.get('key', '')).strip()
    ciphertext = str(data.get('ciphertext', '')).strip()

    if not key_attempt or not ciphertext:
        return jsonify({"error": "Key and ciphertext are required."}), 400

    try:
        fernet_key = derive_fernet_key(key_attempt)
        fernet = Fernet(fernet_key)
        decrypted = fernet.decrypt(ciphertext.encode('utf-8'))
        message = decrypted.decode('utf-8')

        return jsonify({
            "success": True,
            "message": message,
            "explanation": "Key verified: HMAC-SHA256 authentication tag matched and plaintext was successfully recovered."
        })
    except InvalidToken:
        return jsonify({
            "success": False,
            "message": None,
            "explanation": "Key rejected: HMAC-SHA256 authentication failed. Decryption was aborted without revealing plaintext."
        })
    except Exception:
        return jsonify({
            "success": False,
            "message": None,
            "explanation": "Malformed key or invalid ciphertext structure."
        })


