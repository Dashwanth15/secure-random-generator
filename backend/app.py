# 3. NONCE DEMO — FRESHNESS & REPLAY ATTACK DETECTION
# ===========================================================================
@app.route('/api/nonce/verify', methods=['POST'])
def verify_nonce():
    """
    Stateful nonce verification:
    1st submission: Nonce is fresh -> Accept request & record nonce
    2nd submission: Nonce already used -> Reject replay attack!
    """
    global used_nonces
    data = request.get_json(silent=True) or {}
    action = data.get('action', 'send')
    nonce = str(data.get('nonce', '')).strip()

    if action == 'reset':
        used_nonces.clear()
        return jsonify({"status": "RESET", "message": "Nonce cache reset."})

    if not nonce:
        return jsonify({"error": "Nonce cannot be empty."}), 400

    if nonce in used_nonces:
        return jsonify({
            "fresh": False,
            "status": "REJECTED",
            "title": "⚠ Nonce Already Used (Replay Attack Detected)",
            "message": f"Server rejected the request because nonce '{nonce[:8]}...' was already seen in an earlier operation.",
            "request_payload": "Transfer ₹100 to Bob",
            "nonce": nonce,
            "http_status": "409 Conflict (Replay Rejected)"
        })
    else:
        used_nonces.add(nonce)
        return jsonify({
            "fresh": True,
            "status": "ACCEPTED",
            "title": "✓ Fresh / New Nonce Accepted",
            "message": f"Server verified uniqueness of nonce '{nonce[:8]}...'. Transaction processed successfully.",
            "request_payload": "Transfer ₹100 to Bob",
            "nonce": nonce,
            "http_status": "200 OK"
        })


