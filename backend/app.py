# 5. SECURITY TOKEN DEMO — CONSTANT-TIME VERIFICATION
# ===========================================================================
@app.route('/api/token/verify', methods=['POST'])
def verify_token():
    """
    Constant-time token validation using secrets.compare_digest.
    """
    data = request.get_json(silent=True) or {}
    expected_token = str(data.get('expected_token', '')).strip()
    input_token = str(data.get('input_token', '')).strip()

    if not expected_token or not input_token:
        return jsonify({"error": "Both expected token and input token are required."}), 400

    # Constant-time comparison resists timing attacks
    matches = secrets.compare_digest(expected_token, input_token)

    if matches:
        return jsonify({
            "valid": True,
            "status": "VERIFIED",
            "title": "✓ Token Verified",
            "message": "Token matched expected secret value in constant time. Operation authorized.",
            "http_status": "200 OK"
        })
    else:
        diff_count = sum(1 for a, b in zip(expected_token, input_token) if a != b) + abs(len(expected_token) - len(input_token))
        return jsonify({
            "valid": False,
            "status": "INVALID",
            "title": "❌ Token Invalid",
            "message": f"Token mismatch ({diff_count} character(s) different). Operation rejected.",
            "http_status": "403 Forbidden"
        })


