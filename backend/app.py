def derive_fernet_key(key_input: str) -> bytes:
    """
    Derives a standard 32-byte Fernet key from a hex string or arbitrary key string.
    Ensures that the single 64-hex character key string generated by CSPRNG
    is directly used for both encryption and authenticated decryption.
    """
    clean_key = str(key_input).strip()
    # Check if input is valid hexadecimal
    is_hex = len(clean_key) >= 16 and all(c in '0123456789abcdefABCDEF' for c in clean_key)
    
    if is_hex:
        try:
            raw_bytes = bytes.fromhex(clean_key)
            # Pad or trim to exactly 32 bytes (256 bits)
            if len(raw_bytes) != 32:
                raw_bytes = raw_bytes.ljust(32, b'\0')[:32]
            return base64.urlsafe_b64encode(raw_bytes)
        except Exception:
            pass
            
    # Try as direct base64 Fernet key or raw string bytes
    try:
        if len(clean_key) == 44 and clean_key.endswith('='):
            return clean_key.encode('utf-8')
    except Exception:
        pass
        
    return base64.urlsafe_b64encode(clean_key.encode('utf-8').ljust(32, b'\0')[:32])


